def icon(key):
    """Return the inline SVG for a channel key, or a generic link glyph."""
    key = (key or "").lower()
    if key in _ICONS:
        return _FILLED_TPL % _ICONS[key]
    if key in _OUTLINE:
        return _OUTLINE_TPL % _OUTLINE[key]
    return _OUTLINE_TPL % _OUTLINE["link"]


def known_keys():
    return sorted(set(_ICONS) | set(_OUTLINE))
